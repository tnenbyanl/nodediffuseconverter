#include <string>
#include <vector>

void digit_product() {
    int n = 2345;
    int product = 1;
    while (n > 0) {
        product *= (n % 10);
        n /= 10;
    }
    (void)product;
}

void sum_squares() {
    int acc = 0;
    for (int i = -5; i <= 5; ++i) acc += i * i;
    (void)acc;
}

void is_prime() {
    int n = 97;
    bool prime = (n > 1);
    for (int d = 2; d * d <= n; ++d) {
        if (n % d == 0) { prime = false; break; }
    }
    (void)prime;
}

void count_bits() {
    unsigned int n = 0b10110101u;
    int bits = 0;
    while (n != 0) {
        bits += static_cast<int>(n & 1u);
        n >>= 1;
    }
    (void)bits;
}

extern "C" int cedar_delta();
extern "C" void vivid_summit();
extern "C" void golden_quartz();
extern "C" void sable_beacon();

int main() {
    digit_product();
    sum_squares();
    is_prime();
    count_bits();
    vivid_summit();
    golden_quartz();
    sable_beacon();
    return cedar_delta();
}
